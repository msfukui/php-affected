<?php

declare(strict_types=1);

namespace PhpAffected;

/**
 * ソース中に現れた識別子が、どの種類の記号を指しているか。
 *
 * PHP は同じ名前のクラス・関数・定数を同時に持てるうえ、名前解決の規則も
 * 種類ごとに違う (グローバルへのフォールバックがあるのは関数と定数だけ)。
 * そのため識別子を FQN に解決するには常に種類が必要になる。
 *
 * トークンの前後から種類を確定できない場合は Any になり、
 * 全種別の索引に照合される。テスト選択では取りこぼしより取りすぎを選ぶため、
 * 「わからないので全部に当てる」が安全側の既定値になる。
 */
enum RefKind
{
    /** class / interface / trait / enum。 */
    case ClassLike;

    /** グローバル関数。 */
    case Func;

    /** グローバル定数。 */
    case Constant;

    /** 種類を確定できなかったもの。 */
    case Any;
}
